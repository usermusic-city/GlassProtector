#!/usr/bin/env python3
"""生成垃圾代码 DEX（junk.dex）。

输出一个 Java 源文件（stdout），包含 N 个随机命名的类：
- 不透明谓词（opaque predicate）：恒假/恒真条件分支
- 控制流混淆：switch 分发循环
- 随机常量池与字符串

CI 用法：
  python3 scripts/gen_junk.py > /tmp/junk/Junk.java
  javac --release 8 -d /tmp/junk/classes /tmp/junk/Junk.java
  d8 --release --min-api 24 --output /tmp/junk /tmp/junk/classes
  mv /tmp/junk/classes.dex app/src/main/assets/junk.dex
"""
import random
import sys

CLASS_COUNT = 24
METHODS_PER_CLASS = 4

WORDS = ["Glass", "Core", "Util", "Sync", "Render", "Parse", "Cache", "Loop",
         "Mask", "Shift", "Blend", "Probe", "Trace", "Guard", "Seal", "Forge"]


def rnd_name(rng, n=6):
    return "".join(rng.choice("abcdefghijklmnopqrstuvwxyz") for _ in range(n))


def gen_method(rng, idx):
    body = []
    a = rng.randint(1, 0xFFFF)
    b = rng.randint(1, 0xFFFF)
    c = rng.randint(2, 97)
    # 不透明谓词：恒假分支（(x*x+x) 恒为偶数，% 2 == 1 恒假）
    body.append(f"        int x = {a} * q + {b};")
    body.append(f"        if ((x * x + x) % 2 == 1) {{")
    body.append(f"            x ^= {hex(a)};")
    body.append(f"            x = Integer.rotateLeft(x, {rng.randint(1, 31)});")
    body.append("        } else {")
    # 控制流混淆：switch 分发循环
    body.append(f"            int state = q % {c};")
    body.append("            for (int i = 0; i < 3; i++) {")
    body.append("                switch ((state + i) % 3) {")
    body.append("                    case 0: x = x * 31 + 17; break;")
    body.append(f"                    case 1: x ^= {hex(b)}; break;")
    body.append("                    default: x = Integer.reverse(x) >>> {0}; break;".format(rng.randint(1, 15)))
    body.append("                }")
    body.append("            }")
    body.append("        }")
    # 恒真谓词
    body.append(f"        if (((x | {hex(a)}) & 0) == 0) {{ x += {rng.randint(1, 9999)}; }}")
    body.append("        return x;")
    return "\n".join(body)


def gen_class(rng, ci):
    name = WORDS[ci % len(WORDS)] + "_" + rnd_name(rng, 8).capitalize()
    fields = []
    for i in range(3):
        fields.append(f"    private static final int F{i} = {hex(rng.randint(1, 0xFFFFFF))};")
    methods = []
    for mi in range(METHODS_PER_CLASS):
        methods.append(
            f"    public static int m{mi}(int q) {{\n"
            f"{gen_method(rng, mi)}\n"
            f"    }}"
        )
    # 一个长字符串常量方法（污染字符串池）
    junk_str = "".join(rng.choice("0123456789abcdef") for _ in range(64))
    methods.append(
        f"    public static String tag() {{ return \"{junk_str}\"; }}"
    )
    return (f"final class {name} {{\n"
            + "\n".join(fields) + "\n\n"
            + "\n\n".join(methods) + "\n}\n")


def main():
    rng = random.Random()
    rng.seed()  # 每次构建随机
    parts = ["// Auto-generated by scripts/gen_junk.py — junk code injection payload",
             "// 反编译可见：不透明谓词 + 控制流混淆 + 随机常量池", ""]
    for ci in range(CLASS_COUNT):
        parts.append(gen_class(rng, ci))
    sys.stdout.write("\n".join(parts))


if __name__ == "__main__":
    main()
